# frozen_string_literal: true

require "fileutils"
require "yaml"

module RubyStackGovernance
  # Regenerates every agent-facing mirror from the corpus.
  # Law 1: docs/artifacts/** and docs/LAWS.md are the only sources.
  # Law 5: all mirrors are drift-gated by `bin/rake agent:mirror:check`.
  # Law 6: idempotent and byte-stable — no timestamps, deterministic order.
  class AgentMirror
    ROOT = File.expand_path("../..", __dir__)
    MANIFEST = File.join(ROOT, "docs/artifacts/MANIFEST.yml")
    SKILLS_DIR = File.join(ROOT, ".claude/skills")
    RULES_DIR = File.join(ROOT, ".cursor/rules")
    CONTEXT_PATH = File.join(ROOT, "AGENT_CONTEXT.md")
    CURSORRULES_PATH = File.join(ROOT, ".cursorrules")

    HEADER = "<!-- GENERATED by `bin/rake agent:mirror` — DO NOT EDIT (gate: agent_mirror_drift). Source: %<source>s -->"

    # Core rules mirrored into .cursor/rules/00-core.mdc and .cursorrules.
    # Mirrors restate pointers, never numbers (Law 3).
    CORE_DIGEST = <<~CORE
      ## Versions (single sources)

      - Ruby: `.ruby-version` — read it there; never restate a version number in chat, code, or mirrors.
      - Rails: target-app `Gemfile.lock` (~> 7.2 track; 8.1 adopted as the next upgrade — R7).
      - RuboCop: `>= 1.72`, `plugins:` syntax only; `require:` is forbidden.

      ## Six laws (docs/LAWS.md)

      1. Every corpus entry has exactly one deterministic home.
      2. Every home has a ratchet; ratchets only tighten.
      3. Numeric limits have exactly one source — code limits `.rubocop.yml`; Ruby version `.ruby-version`; gem pins `Gemfile.lock`; ratchets `docs/ratchets.yml`; gate commands `config/gates.yml`.
      4. Tool-contract mirrors must be gated — mirrors may exist, lies may not.
      5. Every generated artifact has a drift gate.
      6. Generated output is idempotent — no clocks, byte-stable.

      ## Enforcement (five layers)

      static -> runtime -> process -> agent-context -> agent-interface (docs/ENFORCEMENT.md)

      ## Before proposing changes

      - Read limits with `get_limit`; read ratchet targets with `get_ratchet`; never guess a number.
      - Touching `docs/artifacts/**` or `docs/ratchets.yml`? Run `bin/rake agent:mirror` and commit the mirrors.
      - Boy Scout rule: files a PR touches must exit `.rubocop_todo.yml`.
    CORE

    # Writes every mirror to disk.
    def self.generate!
      render_all.each do |path, body|
        FileUtils.mkdir_p(File.dirname(path))
        File.write(path, body)
      end
    end

    # Pure rendering: { absolute_path => content }. No filesystem writes — this
    # is also the idempotency surface used by spec/mcp/agent_mirror_spec.rb.
    def self.render_all
      artifacts = YAML.safe_load(File.read(MANIFEST), aliases: true)["artifacts"]
      out = { File.join(RULES_DIR, "00-core.mdc") => render_core_rule,
              CURSORRULES_PATH => render_cursorrules }
      artifacts.each do |artifact|
        next unless artifact["mirror"]

        digest = extract_digest(File.join(ROOT, artifact["file"]))
        slug = artifact["skills_slug"]
        out[File.join(SKILLS_DIR, slug, "SKILL.md")] = render_skill(artifact, digest)
        out[File.join(RULES_DIR, "#{slug}.mdc")] = render_rule(artifact, digest)
      end
      out[CONTEXT_PATH] = render_context(artifacts)
      out
    end

    def self.render_skill(artifact, digest)
      <<~SKILL
        ---
        name: #{artifact['skills_slug']}
        description: #{artifact['skill_description']}
        ---

        #{header(artifact['file'])}

        #{digest}
      SKILL
    end

    def self.render_rule(artifact, digest)
      <<~RULE
        ---
        description: #{artifact['skill_description']}
        globs: "#{artifact['globs']}"
        alwaysApply: false
        ---

        #{header(artifact['file'])}

        #{digest}
      RULE
    end

    def self.render_core_rule
      <<~CORE
        ---
        description: Ruby Stack Governance core rules — six laws, version pin sources, enforcement workflow
        globs:
        alwaysApply: true
        ---

        #{header('docs/LAWS.md')}

        #{CORE_DIGEST.strip}
      CORE
    end

    def self.render_cursorrules
      "#{header('docs/LAWS.md')}\n\n#{CORE_DIGEST.strip}\n"
    end

    def self.render_context(artifacts)
      rows = artifacts.map do |a|
        "| #{a['id']} | #{a['title']} | #{a['layer']} | #{Array(a['stacks']).join(', ')} | `#{a['file']}` |"
      end.join("\n")
      <<~CTX
        #{header('docs/artifacts/MANIFEST.yml')}

        # Agent Context Index — Ruby Stack Governance

        Read order: `docs/LAWS.md` -> `docs/ENFORCEMENT.md` -> the artifact that governs the file you are editing. Numbers are never guessed — read the owning file or query via MCP.

        ## Layers

        static -> runtime -> process -> agent-context -> agent-interface

        ## Artifacts

        | ID | Title | Layer | Stacks | File |
        |----|-------|-------|--------|------|
        #{rows}

        ## Numbers (single homes)

        Code limits: `.rubocop.yml`. Ruby version: `.ruby-version`. Gem pins: `Gemfile.lock`. Ratchet targets: `docs/ratchets.yml`. Gate commands: `config/gates.yml`.

        ## Live queries (MCP, stdio, read-only)

        `bin/ruby-stack-governance-mcp` — registered in `.mcp.json` and `.cursor/mcp.json`.
      CTX
    end

    # Extracts the `## Agent Digest` section of an artifact — the artifact
    # body is the only home for skill content (Law 1).
    def self.extract_digest(path)
      match = File.read(path).match(/^## Agent Digest\s*\n(.*?)(?=^## |\z)/m)
      raise ArgumentError, "no `## Agent Digest` section in #{path}" if match.nil?

      match[1].strip
    end

    def self.header(source)
      format(HEADER, source: source)
    end
  end
end
